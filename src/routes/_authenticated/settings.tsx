import { createFileRoute } from "@tanstack/react-router";
import { useQuery, useQueryClient } from "@tanstack/react-query";
import { useEffect, useState } from "react";
import { toast } from "sonner";
import { supabase } from "@/integrations/supabase/client";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Disclaimer } from "@/components/Logo";
import { profileQuery } from "@/lib/data";

export const Route = createFileRoute("/_authenticated/settings")({
  head: () => ({ meta: [{ title: "Settings — AI Study Buddy" }, { name: "description", content: "Manage your study profile." }] }),
  component: SettingsPage,
});

function SettingsPage() {
  const qc = useQueryClient();
  const profile = useQuery(profileQuery);
  const [name, setName] = useState("");
  useEffect(() => { if (profile.data?.display_name) setName(profile.data.display_name); }, [profile.data]);

  async function save(e: React.FormEvent) {
    e.preventDefault();
    if (!name.trim()) { toast.error("Please enter a name"); return; }
    const { data } = await supabase.auth.getUser();
    const { error } = await supabase.from("profiles").upsert({ id: data.user!.id, display_name: name.trim().slice(0, 60) });
    if (error) { toast.error("Couldn't save"); return; }
    qc.invalidateQueries({ queryKey: ["profile"] });
    toast.success("Profile saved");
  }

  return (
    <div className="max-w-xl space-y-6 animate-fade-up">
      <h1 className="text-3xl font-bold">Settings</h1>
      <form onSubmit={save} className="space-y-4 rounded-2xl border bg-card p-6 shadow-card">
        <div className="space-y-1.5"><Label>Email</Label><Input value={profile.data?.email ?? ""} disabled /></div>
        <div className="space-y-1.5"><Label htmlFor="name">Display name</Label><Input id="name" value={name} onChange={(e) => setName(e.target.value)} maxLength={60} /></div>
        <Button type="submit" variant="brand">Save changes</Button>
      </form>
      <div className="rounded-2xl border bg-card p-6 shadow-card">
        <h2 className="font-semibold">About</h2>
        <p className="mt-2 text-sm text-muted-foreground">AI explanations are generated by Lovable AI and may occasionally be wrong — check important details against Microsoft Learn.</p>
        <Disclaimer className="mt-3" />
      </div>
    </div>
  );
}
